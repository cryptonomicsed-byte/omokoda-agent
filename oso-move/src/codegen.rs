#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sanitize_ase_pool() {
        assert_eq!(sanitize_module_name("AsePool"), "ase_pool");
    }

    #[test]
    fn sanitize_agent_registry() {
        assert_eq!(sanitize_module_name("AgentRegistry"), "agent_registry");
    }

    #[test]
    fn is_pascal_valid() {
        assert!(is_pascal_case("AsePool"));
        assert!(is_pascal_case("AgentRegistry"));
        assert!(is_pascal_case("GPUComputeMarketplace"));
    }

    #[test]
    fn is_pascal_invalid() {
        assert!(!is_pascal_case("asePool"));
        assert!(!is_pascal_case(""));
        assert!(!is_pascal_case("_bad"));
    }
}
