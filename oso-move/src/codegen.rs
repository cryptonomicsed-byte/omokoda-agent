/// Sanitize a PascalCase contract name into a snake_case Move module identifier.
/// e.g. "AsePool" → "ase_pool", "AgentRegistry" → "agent_registry"
pub fn sanitize_module_name(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

/// Check that a string satisfies PascalCase: starts with uppercase, alphanumeric only.
fn is_pascal_case(name: &str) -> bool {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) if first.is_ascii_uppercase() => chars.all(|c| c.is_ascii_alphanumeric()),
        _ => false,
    }
}

